const KEY = "kronekort.lang.v1";

export function getLang(): Lang {
  if (typeof window === "undefined") return "no";
  const v = localStorage.getItem(KEY) as Lang | null;
  return v && T[v] ? v : "no";
}
export function setLangStored(l: Lang) {
  if (typeof window !== "undefined") {
    localStorage.setItem(KEY, l);
    window.dispatchEvent(new CustomEvent("kronekort:lang"));
  }
}

export function useLang() {
  const [lang, setLang] = useState<Lang>("no");
  useEffect(() => {
    setLang(getLang());
    const h = () => setLang(getLang());
    window.addEventListener("kronekort:lang", h);
    return () => window.removeEventListener("kronekort:lang", h);
  }, []);
  const t = (k: keyof (typeof T)["no"], vars?: Record<string, string | number>) => {
    let s = T[lang][k] ?? T.no[k] ?? String(k);
    if (vars) for (const [vk, vv] of Object.entries(vars)) s = s.replaceAll(`{${vk}}`, String(vv));
    return s;
  };
  return { lang, setLang: (l: Lang) => { setLangStored(l); setLang(l); }, t };
}
