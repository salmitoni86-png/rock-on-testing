const KEY = "kronekort.lang.v1";

export function getLang(): Lang {
  if (typeof window === "undefined") return "no";
  const v = localStorage.getItem(KEY) as Lang | null;
  return v && T[v] ? v : "no";
}
export function setLangStored(l: Lang) {
  if (typeof window !== "undefined") {
    localStorage.setItem(KEY, l);
    window.dispatchEvent(new CustomEvent("kronekort:lang"));
  }
}

export function formatMoney(n: number, lang: Lang, currency: string = "NOK"): string {
  try {
    return new Intl.NumberFormat(LOCALES[lang], {
      style: "currency",
      currency,
      maximumFractionDigits: 0,
    }).format(n);
  } catch {
    return `${Math.round(n)} ${currency}`;
  }
}

export function formatDate(d: Date | string | number, lang: Lang, opts: Intl.DateTimeFormatOptions = { day: "numeric", month: "short" }): string {
  const date = d instanceof Date ? d : new Date(d);
  try { return new Intl.DateTimeFormat(LOCALES[lang], opts).format(date); }
  catch { return date.toLocaleDateString(); }
}

export function formatShortWeekday(d: Date, lang: Lang): string {
  return formatDate(d, lang, { weekday: "short", day: "numeric" });
}

export function useLang() {
  const [lang, setLang] = useState<Lang>("no");
  useEffect(() => {
    setLang(getLang());
    const h = () => setLang(getLang());
    window.addEventListener("kronekort:lang", h);
    return () => window.removeEventListener("kronekort:lang", h);
  }, []);
  const t = (k: keyof (typeof T)["no"] | string, vars?: Record<string, string | number>) => {
    const key = k as keyof (typeof T)["no"];
    let s = T[lang][key] ?? T.no[key] ?? String(k);
    if (vars) for (const [vk, vv] of Object.entries(vars)) s = s.replaceAll(`{${vk}}`, String(vv));
    return s;
  };
  const fmt = useMemo(() => ({
    money: (n: number) => formatMoney(n, lang),
    date: (d: Date | string | number, o?: Intl.DateTimeFormatOptions) => formatDate(d, lang, o),
    shortWeekday: (d: Date) => formatShortWeekday(d, lang),
    locale: LOCALES[lang],
  }), [lang]);
  return { lang, setLang: (l: Lang) => { setLangStored(l); setLang(l); }, t, fmt };
}
